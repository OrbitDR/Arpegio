function append(parent, children) {
  for (const child of children) {
    if (child === null || child === undefined || child === false) continue;
    if (Array.isArray(child)) append(parent, child);
    else parent.append(child);
  }
}

// The DOM's own append() would write a skipped child as the text "null".
export function fill(parent, ...children) {
  append(parent, children);
}

// h('div.card.wide', { onclick: fn, title: 'x' }, child, 'text', [more])
export function h(spec, props, ...children) {
  const [tag, ...classes] = spec.split('.');
  const element = document.createElement(tag || 'div');
  if (classes.length) element.className = classes.join(' ');

  const isProps = props && typeof props === 'object' && !Array.isArray(props) && !(props instanceof Node);
  if (!isProps) children.unshift(props);
  else {
    for (const [key, value] of Object.entries(props)) {
      if (value === undefined || value === null) continue;
      if (key.startsWith('on')) element.addEventListener(key.slice(2), value);
      else if (key === 'class') element.classList.add(...value.split(' ').filter(Boolean));
      else if (key === 'style') Object.assign(element.style, value);
      else if (key === 'dataset') Object.assign(element.dataset, value);
      else if (key in element) element[key] = value;
      else if (value !== false) element.setAttribute(key, value === true ? '' : value);
    }
  }
  append(element, children);
  return element;
}

export function icon(name, size = 20) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', size);
  svg.setAttribute('height', size);
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('aria-hidden', 'true');
  for (const part of [ICONS[name]].flat()) {
    const path = document.createElementNS(SVG_NS, 'path');
    path.setAttribute('d', part);
    svg.append(path);
  }
  return svg;
}

export function iconButton(name, label, onclick, { size = 20, cls = '' } = {}) {
  return h('button.icon-button', { type: 'button', title: label, ariaLabel: label, onclick, class: cls, dataset: { icon: name } },
    icon(name, size));
}

// The player bar calls this on every status update, so the page only changes when the icon does.
export function setIcon(button, name, size = 20) {
  if (button.dataset.icon === name) return;
  button.dataset.icon = name;
  button.replaceChildren(icon(name, size));
}

export function clear(element) {
  element.replaceChildren();
}
